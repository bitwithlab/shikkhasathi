#!/usr/bin/env node
// Generates design-token outputs from website/src/styles/tokens/tokens.json:
//  - website/src/styles/tokens/tokens.gen.css  (CSS variables for light/dark + Tailwind v4 @theme preset)
//  - app/shared/src/commonMain/kotlin/com/shikkhasathi/core/designsystem/Tokens.kt (Compose theme constants)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'website/src/styles/tokens/tokens.json'), 'utf8'));
const header = '/* AUTO-GENERATED by scripts/gen-tokens.mjs — do not edit. Source: tokens.json */\n';

// ---------- CSS ----------
const vars = (set) =>
  Object.entries(set)
    .map(([k, v]) => `  --ss-${k}: ${v};`)
    .join('\n');
const colorNames = Object.keys(tokens.color.light);
let css = header;
css += `:root {\n${vars(tokens.color.light)}\n  color-scheme: light;\n}\n`;
css += `:root[data-theme='dark'] {\n${vars(tokens.color.dark)}\n  color-scheme: dark;\n}\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${vars(tokens.color.dark)
  .split('\n')
  .map((l) => '  ' + l)
  .join('\n')}\n    color-scheme: dark;\n  }\n}\n`;
css += `@theme {\n`;
for (const n of colorNames) css += `  --color-${n}: var(--ss-${n});\n`;
for (const [k, v] of Object.entries(tokens.radius)) css += `  --radius-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(tokens.fontSize)) css += `  --text-${k}: ${v / 16}rem;\n`;
for (const [k, v] of Object.entries(tokens.shadow)) css += `  --shadow-e${k}: ${v};\n`;
css += `  --font-sans: ${tokens.font.sans};\n  --font-latin: ${tokens.font.latin};\n`;
css += `  --ease-ss: ${tokens.motion.easing};\n`;
css += `}\n`;
css += `:root {\n  --ss-gradient-brand: ${tokens.gradient.brand};\n  --ss-motion-fast: ${tokens.motion.fast}ms;\n  --ss-motion-base: ${tokens.motion.base}ms;\n}\n`;
writeFileSync(resolve(root, 'website/src/styles/tokens/tokens.gen.css'), css);

// ---------- Compose ----------
const hex = (v) => {
  const h = v.replace('#', '');
  return `Color(0xFF${h.toUpperCase()})`;
};
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pkg = 'com.shikkhasathi.core.designsystem';
let kt = `// AUTO-GENERATED by scripts/gen-tokens.mjs — do not edit. Source: website/src/styles/tokens/tokens.json\npackage ${pkg}\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\n\n`;
for (const mode of ['light', 'dark']) {
  kt += `object Ss${mode[0].toUpperCase() + mode.slice(1)}Colors {\n`;
  for (const [k, v] of Object.entries(tokens.color[mode])) kt += `    val ${camel(k)} = ${hex(v)}\n`;
  kt += `}\n\n`;
}
kt += `object SsRadius {\n`;
for (const [k, v] of Object.entries(tokens.radius)) kt += `    val ${camel(k)} = ${Math.min(v, 999)}.dp\n`;
kt += `}\n\nobject SsSpace {\n`;
for (const [k, v] of Object.entries(tokens.space)) kt += `    val s${k} = ${v}.dp\n`;
kt += `}\n\nobject SsFontSize {\n`;
for (const [k, v] of Object.entries(tokens.fontSize)) kt += `    val ${k.replace(/^(\d)/, 'x$1')} = ${v}.sp\n`;
kt += `}\n\nconst val SS_BANGLA_LINE_HEIGHT = ${tokens.font.lineHeightBangla}f\nconst val SS_MOTION_BASE_MS = ${tokens.motion.base}\n`;
const ktDir = resolve(root, 'app/shared/src/commonMain/kotlin/com/shikkhasathi/core/designsystem');
mkdirSync(ktDir, { recursive: true });
writeFileSync(resolve(ktDir, 'Tokens.kt'), kt);
console.info('tokens generated: CSS + Compose');
